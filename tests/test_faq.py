"""
Тесты для раздела «Вопросы о важном» (FAQ).

Проверяем: при клике на стрелку каждого вопроса открывается
соответствующий текст ответа.

Используется параметризация — один тест для всех 8 вопросов.
"""

import allure
import pytest
from pages.main_page import MainPage


# Данные для параметризации: (индекс вопроса, текст вопроса, ожидаемый фрагмент ответа)
FAQ_DATA = [
    (0,
     "Сколько это стоит? И как оплатить?",
     "400 рублей"),
    (1,
     "Хочу сразу несколько самокатов! Так можно?",
     "один заказ — один самокат"),
    (2,
     "Как рассчитывается время аренды?",
     "Отсчёт времени аренды"),
    (3,
     "Можно ли заказать самокат прямо на сегодня?",
     "начиная с завтрашнего дня"),
    (4,
     "Можно ли продлить заказ или вернуть самокат раньше?",
     "Пока что нет"),
    (5,
     "Вы привозите зарядку вместе с самокатом?",
     "полной зарядкой"),
    (6,
     "Можно ли отменить заказ?",
     "пока самокат не привезли"),
    (7,
     "Я жизу за МКАДом, привезёте?",
     "Да, обязательно"),
]


@allure.feature("FAQ — Вопросы о важном")
class TestFAQ:
    """Тесты выпадающего списка FAQ."""

    @allure.title("Вопрос {index}: '{question}' — проверка открытия ответа")
    @pytest.mark.parametrize("index, question, expected_text", FAQ_DATA)
    def test_faq_question_opens_answer(self, driver, index, question, expected_text):
        """
        Проверяем, что при клике на вопрос FAQ открывается текст ответа,
        содержащий ожидаемый фрагмент.
        """
        with allure.step("Открыть главную страницу"):
            page = MainPage(driver)
            page.open()

        with allure.step(f"Прокрутить до вопроса №{index + 1}: «{question}»"):
            page.click_faq_question(index)

        with allure.step(f"Проверить, что ответ содержит: «{expected_text}»"):
            answer_text = page.get_faq_answer_text(index)
            assert expected_text in answer_text, (
                f"Ожидали увидеть «{expected_text}» в ответе на вопрос «{question}», "
                f"но получили: «{answer_text}»"
            )
